export const translateGroceryCategory = (category: string, t: LocaleContextValue["t"]) => {
  const map: Record<string, string> = {
    Dairy: "category.dairy",
    Vegetables: "category.vegetables",
    Fruit: "category.fruit",
    Meat: "category.meat",
    Bakery: "category.bakery",
    Pantry: "category.pantry",
    Frozen: "category.frozen",
    Snacks: "category.snacks",
  };

  if (!map[category]) {
    return category;
  }

  const translated = t(map[category]);
  return translated === map[category] ? category : translated;
};

